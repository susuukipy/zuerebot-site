    local ok,settings=pcall(function() return HttpService:JSONDecode(readfile("DOLL404_settings.json")) end)
    if not ok or type(settings)~="table" then return false end
    for key,value in pairs(settings) do if S[key]~=nil and type(value)==type(S[key]) then S[key]=value end end
    for _,refresh in pairs(Toggles) do refresh() end
    for _,refresh in pairs(Sliders) do refresh() end
