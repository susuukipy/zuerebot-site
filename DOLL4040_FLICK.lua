local function enemy(player)
    if player==LocalPlayer then return false end
    if S.TeamCheck and not LocalPlayer.Neutral and not player.Neutral and LocalPlayer.Team~=nil and player.Team==LocalPlayer.Team then return false end
    return true
end
local function findPart(character,names)
    if not character then return nil end
    for _,name in ipairs(names) do
        local part=character:FindFirstChild(name,true)
        if part and part:IsA("BasePart") then return part end
    end
    if character.PrimaryPart and character.PrimaryPart:IsA("BasePart") then return character.PrimaryPart end
    return character:FindFirstChildWhichIsA("BasePart",true)
end
local function getRig(player)
    local character=player.Character
    if not character or not character.Parent then
        local possible=workspace:FindFirstChild(player.Name)
        if possible and possible:IsA("Model") then character=possible end
    end
    if not character then return nil end
    local root=findPart(character,{"HumanoidRootPart","LowerTorso","Torso","UpperTorso","Head"})
    local head=findPart(character,{"Head","UpperTorso","Torso","HumanoidRootPart"})
    local humanoid=character:FindFirstChildOfClass("Humanoid") or character:FindFirstChildWhichIsA("Humanoid",true)
    if humanoid and humanoid.Health<=0 then return nil end
    if not root or not head then return nil end
    return character,root,head,humanoid
end
local function visibleThroughRay(character,point)
    local camera=workspace.CurrentCamera
    if not camera then return false end
    local delta=point-camera.CFrame.Position
    local parameters=RaycastParams.new()
    parameters.FilterType=Enum.RaycastFilterType.Exclude
    local ignore={camera}
    if LocalPlayer.Character then table.insert(ignore,LocalPlayer.Character) end
    parameters.FilterDescendantsInstances=ignore
    local result=workspace:Raycast(camera.CFrame.Position,delta,parameters)
    return result==nil or (result.Instance and result.Instance:IsDescendantOf(character))
end
local function vertices(center,size)
    local half=size*.5
    return {
        center*CFrame.new(-half.X,-half.Y,-half.Z),
        center*CFrame.new(half.X,-half.Y,-half.Z),
        center*CFrame.new(half.X,half.Y,-half.Z),
        center*CFrame.new(-half.X,half.Y,-half.Z),
        center*CFrame.new(-half.X,-half.Y,half.Z),
        center*CFrame.new(half.X,-half.Y,half.Z),
        center*CFrame.new(half.X,half.Y,half.Z),
        center*CFrame.new(-half.X,half.Y,half.Z)
    }
end
local function updateESP(camera,screen)
    local rigCount=0
    local visibleCount=0
    for _,player in ipairs(Players:GetPlayers()) do
        if player~=LocalPlayer then
            local o=objectFor(player)
            hide(o)
            if S.ESP and enemy(player) then
                local character,root,head,humanoid=getRig(player)
                if character then
                    rigCount=rigCount+1
                    local distance=(camera.CFrame.Position-root.Position).Magnitude
                    if distance<=S.MaxESPDistance then
                        if S.Wallhack then
                            if o.CurrentCharacter~=character then
                                pcall(function() o.Highlight:Destroy() end)
                                o.Highlight=new("Highlight",{Name="DOLL404_Wallhack",FillColor=White,OutlineColor=White,FillTransparency=.68,OutlineTransparency=0,DepthMode=Enum.HighlightDepthMode.AlwaysOnTop,Enabled=false},nil)
                                o.CurrentCharacter=character
                            end
                            o.Highlight.Adornee=character
                            if o.Highlight.Parent~=character then o.Highlight.Parent=character end
                            o.Highlight.Enabled=true
                        end
                        local centerPoint,onScreen=camera:WorldToViewportPoint(root.Position)
                        if centerPoint.Z>.05 and onScreen then
                            visibleCount=visibleCount+1
                            local boxCenter=root.CFrame*CFrame.new(0,.25,0)
                            local boxSize=Vector3.new(4.15,6.5,3.2)
                            local corners=vertices(boxCenter,boxSize)
                            local points={}
                            local valid=true
                            local xMin,xMax,yMin,yMax=math.huge,-math.huge,math.huge,-math.huge
                            for i,cf in ipairs(corners) do
                                local p=camera:WorldToViewportPoint(cf.Position)
                                if p.Z<=.05 then valid=false break end
                                points[i]=Vector2.new(p.X,p.Y)
                                xMin=math.min(xMin,p.X)
                                xMax=math.max(xMax,p.X)
                                yMin=math.min(yMin,p.Y)
                                yMax=math.max(yMax,p.Y)
                            end
                            if valid then
                                if S.ESP3D then
                                    for i,pair in ipairs(SegmentPairs) do
                                        positionLine(o.Lines[i],points[pair[1]],points[pair[2]],1.5,White)
                                    end
                                end
                                if S.ESP2D then
                                    local rect={Vector2.new(xMin,yMin),Vector2.new(xMax,yMin),Vector2.new(xMax,yMax),Vector2.new(xMin,yMax)}
                                    for i=1,4 do positionLine(o.Box2D[i],rect[i],rect[i%4+1],1,Muted) end
                                end
                            end
                            local top=camera:WorldToViewportPoint(head.Position+Vector3.new(0,.75,0))
                            local bottom=camera:WorldToViewportPoint(root.Position-Vector3.new(0,3,0))
                            local bodyHeight=math.clamp(math.abs(bottom.Y-top.Y),20,1000)
                            local bodyWidth=bodyHeight*.5
                            if S.Tracers then positionLine(o.Tracer,Vector2.new(screen.X*.5,screen.Y-12),Vector2.new(centerPoint.X,centerPoint.Y),1,Muted) end
                            if S.Names or S.Distance then
                                o.Name.Visible=true
                                local name=S.Names and player.DisplayName or ""
                                if S.Distance then name=name.."  ["..math.floor(distance).." studs]" end
                                o.Name.Text=name
                                o.Name.Position=UDim2.fromOffset(top.X-100,top.Y-29)
                            end
                            if S.Health and humanoid then
                                local pct=math.clamp(humanoid.Health/math.max(humanoid.MaxHealth,1),0,1)
                                o.HealthBack.Position=UDim2.fromOffset(centerPoint.X-bodyWidth*.5-10,top.Y)
                                o.HealthBack.Size=UDim2.fromOffset(4,bodyHeight)
                                o.HealthBack.Visible=true
                                o.HealthFill.AnchorPoint=Vector2.new(0,1)
                                o.HealthFill.Position=UDim2.fromScale(0,1)
                                o.HealthFill.Size=UDim2.fromScale(1,pct)
                            end
                            if S.Skeleton then
                                local used=0
                                for _,pair in ipairs(SkeletonPairs) do
                                    local a=character:FindFirstChild(pair[1],true)
                                    local b=character:FindFirstChild(pair[2],true)
                                    if a and b and a:IsA("BasePart") and b:IsA("BasePart") then
                                        local pa=camera:WorldToViewportPoint(a.Position)
                                        local pb=camera:WorldToViewportPoint(b.Position)
                                        if pa.Z>0 and pb.Z>0 then
                                            used=used+1
                                            if o.Skeleton[used] then positionLine(o.Skeleton[used],Vector2.new(pa.X,pa.Y),Vector2.new(pb.X,pb.Y),1.4,Muted) end
                                        end
                                    end
                                end
                            end
                        elseif S.Offscreen then
                            local localPosition=camera.CFrame:PointToObjectSpace(root.Position)
                            local direction=Vector2.new(localPosition.X,-localPosition.Y)
                            if localPosition.Z>0 then direction=-direction end
                            if direction.Magnitude>.1 then
                                local unit=direction.Unit
                                local rx=math.min(screen.X*.42,380)
                                local ry=math.min(screen.Y*.37,220)
                                o.Offscreen.Position=UDim2.fromOffset(screen.X*.5+unit.X*rx-13,screen.Y*.5+unit.Y*ry-13)
                                o.Offscreen.Rotation=math.deg(math.atan2(unit.Y,unit.X))+90
                                o.Offscreen.Visible=true
                            end
                        end
                    end
                end
            end
        end
    end
    State.RigCount=rigCount
    State.VisibleCount=visibleCount
end
local function updateAim(camera,view,dt)
    if not S.Aim then State.AimStatus="Aim desligado" return end
    if UIS:GetFocusedTextBox() then State.AimStatus="Campo de texto aberto" return end
    local held=S.AutoAim or State.AimHeld or UIS:IsMouseButtonPressed(Enum.UserInputType.MouseButton2)
    if not held then State.AimStatus="Segure RMB ou ligue Auto Aim" return end
    local center=Vector2.new(view.X*.5,view.Y*.5)
    local nearest=S.FOV
    local best=nil
    local bestScreen=nil
    local sticky=State.LastTarget
    local stickyValid=false
    local stickyScreen=nil
    local rigCount=0
    for _,player in ipairs(Players:GetPlayers()) do
        if enemy(player) then
            local ch,root,head=getRig(player)
            if ch then
                rigCount=rigCount+1
                local target=ch:FindFirstChild(S.AimPart,true)
                if not target or not target:IsA("BasePart") then target=head or root end
                if (target.Position-camera.CFrame.Position).Magnitude<=S.AimDistance then
                    local projection,inView=camera:WorldToViewportPoint(target.Position)
                    if inView and projection.Z>0 then
                        local distance=(Vector2.new(projection.X,projection.Y)-center).Magnitude
                        if distance<nearest and (not S.AimWallCheck or visibleThroughRay(ch,target.Position)) then
                            nearest=distance
                            best=target
                            bestScreen=Vector2.new(projection.X,projection.Y)
                        end
                        if S.StickyAim and sticky==target and distance<S.FOV*1.2 and (not S.AimWallCheck or visibleThroughRay(ch,target.Position)) then
                            stickyValid=true
                            stickyScreen=Vector2.new(projection.X,projection.Y)
                        end
                    end
                end
            end
        end
    end
    if stickyValid and sticky and sticky.Parent then
        best=sticky
        bestScreen=stickyScreen
    end
    if not best then
        State.LastTarget=nil
        State.AimStatus=rigCount==0 and "Nenhum rig replicado" or "Sem alvo no FOV"
        return
    end
    State.LastAimPart=best
    State.LastTarget=best
    if (S.MouseAim or S.AutoMouseAim) and type(mousemoverel)=="function" then
        local displacement=(bestScreen-center)*math.clamp(S.MouseSensitivity,0.05,1.6)*math.clamp(dt*60,0.25,1.5)
        local ok=pcall(function() mousemoverel(displacement.X,displacement.Y) end)
        State.AimStatus=ok and "Mira via mouse" or "mousemoverel falhou"
    else
        local desired=CFrame.lookAt(camera.CFrame.Position,best.Position)
        camera.CFrame=camera.CFrame:Lerp(desired,math.clamp(S.Smooth*dt*60,.025,1))
        State.AimStatus="Alvo: "..best.Parent.Name.." | Camera"
    end
end
local function restoreEffects()
    for obj,properties in pairs(State.Originals) do
        if obj and obj.Parent then for prop,value in pairs(properties) do pcall(function() obj[prop]=value end) end end
    end
    State.Originals={}
end
local function setEffect(obj,property,value)
    if not State.Originals[obj] then State.Originals[obj]={} end
    if State.Originals[obj][property]==nil then
        local ok,old=pcall(function() return obj[property] end)
        if ok then State.Originals[obj][property]=old end
    end
    pcall(function() obj[property]=value end)
end
local function tuneEffect(obj)
    if obj:IsA("ParticleEmitter") or obj:IsA("Trail") or obj:IsA("Beam") or obj:IsA("Smoke") or obj:IsA("Fire") or obj:IsA("Sparkles") then
        setEffect(obj,"Enabled",false)
    elseif obj:IsA("BloomEffect") or obj:IsA("DepthOfFieldEffect") or obj:IsA("SunRaysEffect") or obj:IsA("BlurEffect") then
        setEffect(obj,"Enabled",false)
    end
end
local function applyPerformance(enabled)
    if enabled then
        setEffect(Lighting,"GlobalShadows",false)
        for _,obj in ipairs(workspace:GetDescendants()) do tuneEffect(obj) end
        for _,obj in ipairs(Lighting:GetDescendants()) do tuneEffect(obj) end
    else restoreEffects() end
end
