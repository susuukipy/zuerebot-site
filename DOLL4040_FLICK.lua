local function base64decode(value)
    local alphabet="ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    local lookup={}
    for i=1,string.len(alphabet) do lookup[string.sub(alphabet,i,i)]=i-1 end
    local bytes={}
    local buffer=0
    local bits=0
    for i=1,string.len(value) do
        local n=lookup[string.sub(value,i,i)]
        if n~=nil then
            buffer=buffer*64+n
            bits=bits+6
            if bits>=8 then
                bits=bits-8
                table.insert(bytes,string.char(math.floor(buffer/(2^bits))%256))
                buffer=buffer%(2^bits)
            end
        end
    end
    return table.concat(bytes)
end
local function prepareBanner()
    if type(writefile)~="function" then return end
    if type(isfile)=="function" then
        local ok,exists=pcall(isfile,"DOLL404/banner.jpg")
        if ok and exists then return end
    end
    if type(makefolder)=="function" then pcall(makefolder,"DOLL404") end
    local bytes=base64decode(EmbeddedBanner)
    pcall(writefile,"DOLL404/banner.jpg",bytes)
    EmbeddedBanner=""
end
local function getBanner()
    if S.BannerId~="" then
        local id=string.match(S.BannerId,"%d+")
        if id then return "rbxassetid://"..id end
    end
    if type(getcustomasset)=="function" and type(isfile)=="function" then
        local ok,result=pcall(function()
            if isfile(S.BannerPath) then return getcustomasset(S.BannerPath) end
        end)
        if ok and type(result)=="string" then return result end
    end
    if type(getsynasset)=="function" and type(isfile)=="function" then
        local ok,result=pcall(function()
            if isfile(S.BannerPath) then return getsynasset(S.BannerPath) end
        end)
        if ok and type(result)=="string" then return result end
    end
    return ""
end
