local function slider(parent,title,description,key,min,max,step,suffix)
    local row=card(parent,76)
    label(row,title,12,UDim2.fromOffset(13,7),UDim2.new(1,-122,0,20),White,Enum.Font.GothamBold)
    label(row,description,10,UDim2.fromOffset(13,27),UDim2.new(1,-28,0,16),Muted,Enum.Font.Gotham)
    local value=label(row,"",12,UDim2.new(1,-103,0,8),UDim2.fromOffset(88,18),White,Enum.Font.GothamBold)
    value.TextXAlignment=Enum.TextXAlignment.Right
    local track=new("Frame",{Position=UDim2.fromOffset(14,59),Size=UDim2.new(1,-28,0,5),BackgroundColor3=Color3.fromRGB(72,72,82),BorderSizePixel=0},row)
    rounded(track,3)
    local fill=new("Frame",{Size=UDim2.fromScale(0,1),BackgroundColor3=White,BorderSizePixel=0},track)
    rounded(fill,3)
    local dot=new("Frame",{AnchorPoint=Vector2.new(.5,.5),Position=UDim2.new(0,0,.5,0),Size=UDim2.fromOffset(13,13),BackgroundColor3=White,BorderSizePixel=0},track)
    rounded(dot,7)
    local dragging=false
    local function refresh()
        local percent=math.clamp((S[key]-min)/(max-min),0,1)
        value.Text=tostring(S[key])..(suffix or "")
        fill.Size=UDim2.fromScale(percent,1)
        dot.Position=UDim2.new(percent,0,.5,0)
    end
    local function setAt(x)
        local width=math.max(track.AbsoluteSize.X,1)
        local ratio=math.clamp((x-track.AbsolutePosition.X)/width,0,1)
        local result=min+math.floor(((max-min)*ratio)/step+.5)*step
        S[key]=math.clamp(math.floor(result*1000+.5)/1000,min,max)
        refresh()
    end
    connect(track.InputBegan,function(input)
        if input.UserInputType==Enum.UserInputType.MouseButton1 or input.UserInputType==Enum.UserInputType.Touch then dragging=true setAt(input.Position.X) end
    end)
    connect(UIS.InputChanged,function(input)
        if dragging and (input.UserInputType==Enum.UserInputType.MouseMovement or input.UserInputType==Enum.UserInputType.Touch) then setAt(input.Position.X) end
    end)
    connect(UIS.InputEnded,function(input)
        if input.UserInputType==Enum.UserInputType.MouseButton1 or input.UserInputType==Enum.UserInputType.Touch then if dragging and queueSave then queueSave() end dragging=false end
    end)
    Sliders[key]=refresh
    refresh()
    return row
end
